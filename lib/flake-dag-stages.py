#!/usr/bin/env python3
"""Two-stage generated check DAG: independent roots fan out, dependent roots join.

The actual Nix derivation DAG is generated by flake-check-dag.py. This adapts
its check-level dependency projection to a bounded GitHub Actions matrix.
Every check runs exactly once; store closures move between isolated runners
using integrity-checked Nix export/import archives. No second test registry.
"""
import argparse
import importlib.util
import json
import os
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).parent
def module(name, filename):
    spec = importlib.util.spec_from_file_location(name, ROOT / filename)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod

planner = module("flake_check_plan_stages", "flake-check-plan.py")
dag = module("flake_check_dag_stages", "flake-check-dag.py")
SCHEMA = 1

def load(path):
    return json.loads(Path(path).read_text())

def save(path, data):
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text(planner.canonical(data) + "\n")

def partition(plan, graph):
    planner.validate_plan(plan)
    if (graph.get("schemaVersion") != SCHEMA
            or graph.get("planDigest") != plan["digest"]
            or graph.get("commit") != plan["commit"]
            or graph.get("system") != plan["system"]
            or not isinstance(graph.get("checkDependencies"), dict)
            or set(graph["checkDependencies"]) != set(plan["checks"])):
        raise ValueError("invalid or stale derived DAG")
    deps = graph["checkDependencies"]
    for name, names in deps.items():
        if (not isinstance(names, list) or len(set(names)) != len(names)
                or not set(names) <= (set(deps) - {name})):
            raise ValueError(f"invalid derived check dependencies for {name}")
    # A check with dependencies must run after the initial fan-out stage.
    # This includes shipping but is not specific to shipping or Rust.
    initial = {name for name, values in deps.items() if not values}
    delayed = sorted(set(deps) - initial)
    # Existing deterministic weighted shards remain the source of check
    # placements. Remove delayed checks but don't lose any leaf roots.
    shards = [
        {"id": shard["id"], "checks": [name for name in shard["checks"] if name in initial]}
        for shard in plan["shards"]
    ]
    shards = [s for s in shards if s["checks"]]
    if set(name for s in shards for name in s["checks"]) != initial:
        raise ValueError("fan-out shards do not cover all ready check roots")
    # Subsequent dependent checks are built in one Nix invocation, which
    # internally unlocks ready nodes concurrently as prior nodes finish.
    result = {
        "schemaVersion": SCHEMA, "commit": plan["commit"],
        "planDigest": plan["digest"], "graphDigest": graph["graphDigest"],
        "shards": shards, "finalChecks": delayed,
        "initialChecks": sorted(initial),
    }
    result["digest"] = planner.digest(result)
    return result

def validated(args):
    plan, graph, stages = load(args.plan), load(args.graph), load(args.stages)
    if stages != partition(plan, graph):
        raise ValueError("stale, forged or mismatched stage manifest")
    return plan, graph, stages

def plan_command(args):
    plan, graph = load(args.plan), load(args.graph)
    stages = partition(plan, graph)
    save(args.output, stages)
    if os.getenv("GITHUB_OUTPUT"):
        with open(os.environ["GITHUB_OUTPUT"], "a", encoding="utf-8") as f:
            f.write("matrix=" + planner.canonical({
                "include": [{"id": shard["id"]} for shard in stages["shards"]]
            }) + "\n")
            f.write("stage_digest=" + stages["digest"] + "\n")
    print(f"Stages: {len(stages['shards'])} independent worker shards, "
          f"{len(stages['finalChecks'])} dependent checks in final Nix join")

def ensure_commit(plan):
    if planner.run_command(["git", "rev-parse", "HEAD"]) != plan["commit"]:
        raise ValueError("worker checkout does not match exact-head DAG")

def build_selected(plan, names):
    if not names:
        return {}
    if len(names) != len(set(names)) or not set(names) <= set(plan["checks"]):
        raise ValueError("duplicate or undeclared selected check")
    subset = {name: plan["checks"][name] for name in sorted(names)}
    targets = [f".#checks.{plan['system']}.{name}" for name in sorted(names)]
    # One Nix invocation for every ready root in this worker: Nix schedules
    # the entire dependency DAG concurrently and builds identical .drv paths
    # only once, rather than serializing one nix build per named check.
    raw = subprocess.check_output(
        ["nix", "build", "--no-link", "--json", "-L", *targets], text=True)
    realized = dag.parse_nix_results(json.loads(raw), subset)
    return {
        name: {"drv": drv, "status": "pass", "outputs": realized[drv]}
        for name, drv in subset.items()
    }

def evidence(plan, stages, role, checks):
    return {
        "schemaVersion": SCHEMA, "role": role, "commit": plan["commit"],
        "planDigest": plan["digest"], "stageDigest": stages["digest"],
        "graphDigest": stages["graphDigest"], "checks": checks,
    }

def shared_outputs(path):
    shared = load(path)
    outputs = shared.get("outputs")
    if not isinstance(outputs, dict):
        raise ValueError("shared prebuild evidence lacks outputs")
    values = [x for group in outputs.values() for x in group]
    if not all(isinstance(x, str) and planner.STORE.fullmatch(x) for x in values):
        raise ValueError("invalid shared Nix store outputs")
    return sorted(set(values))

def closure(paths):
    if not paths:
        return set()
    items = planner.run_command(["nix-store", "--query", "--requisites", *paths]).splitlines()
    if not all(planner.STORE.fullmatch(x) for x in items):
        raise ValueError("Nix reported invalid store closure")
    # Preserve Nix's requisites order for a valid self-contained export.
    return list(dict.fromkeys(items))

def export_incremental_archive(checks, shared, filename):
    """Export new objects in dependency order, excluding the shared closure."""
    roots = sorted(set(out for item in checks.values() for out in item["outputs"]))
    excluded = set(closure(shared))
    incremental = [item for item in closure(roots) if item not in excluded]
    target = Path(filename)
    target.parent.mkdir(parents=True, exist_ok=True)
    # Encode a complete independent delta: a consumer restores shared closure
    # first, then imports this artifact. Nix checks NAR store-path integrity.
    if incremental:
        with target.open("wb") as f:
            subprocess.run(["nix-store", "--export", *incremental],
                           check=True, stdout=f)
    else:
        target.write_bytes(b"")
    return incremental

def leaf_command(args):
    plan, _, stages = validated(args)
    ensure_commit(plan)
    target = next((s for s in stages["shards"] if s["id"] == args.shard), None)
    if target is None:
        raise ValueError("unplanned leaf shard")
    checks = build_selected(plan, target["checks"])
    incremental = export_incremental_archive(checks, shared_outputs(args.prebuild), args.archive)
    out = evidence(plan, stages, args.shard, checks)
    out["exportedPaths"] = incremental
    save(args.output, out)
    print(f"Leaf {args.shard}: {len(checks)} checks; {len(incremental)} incremental store paths")

def verify_leaf(plan, stages, item):
    if any(item.get(k) != value for k, value in {
        "schemaVersion": SCHEMA, "commit": plan["commit"],
        "planDigest": plan["digest"], "stageDigest": stages["digest"],
        "graphDigest": stages["graphDigest"],
    }.items()):
        raise ValueError("stale leaf evidence")
    matching = [s for s in stages["shards"] if s["id"] == item.get("role")]
    if len(matching) != 1 or set(item.get("checks", {})) != set(matching[0]["checks"]):
        raise ValueError("missing or duplicate leaf check evidence")
    for name, check in item["checks"].items():
        if (check.get("status") != "pass" or check.get("drv") != plan["checks"][name]
                or not check.get("outputs")
                or not all(planner.STORE.fullmatch(x) for x in check["outputs"])):
            raise ValueError(f"invalid leaf result {name}")

def join_command(args):
    plan, graph, stages = validated(args)
    ensure_commit(plan)
    folder = Path(args.leaves)
    files = sorted(folder.rglob("evidence.json"))
    if len(files) != len(stages["shards"]):
        raise ValueError("missing fan-out worker evidence")
    seen, results = set(), {}
    for path in files:
        item = load(path)
        verify_leaf(plan, stages, item)
        if item["role"] in seen:
            raise ValueError("duplicate shard in join")
        seen.add(item["role"])
        archive = path.with_name("store.nar")
        if not archive.is_file():
            raise ValueError(f"missing store transfer from {item['role']}")
        if archive.stat().st_size:
            with archive.open("rb") as source:
                subprocess.run(["nix-store", "--import"], stdin=source, check=True,
                               stdout=subprocess.DEVNULL)
        results.update(item["checks"])
    for item in results.values():
        # Fail rather than rebuilding any dependency already built by a leaf.
        paths = item["outputs"]
        existing = planner.run_command(["nix", "path-info", "--offline", *paths]).splitlines()
        if set(existing) != set(paths):
            raise ValueError("missing realized fan-out outputs after import")
    terminal = build_selected(plan, stages["finalChecks"])
    if set(results) & set(terminal):
        raise ValueError("duplicate named check built twice")
    results.update(terminal)
    if set(results) != set(plan["checks"]):
        raise ValueError("incomplete joined check inventory")
    out = evidence(plan, stages, "join", results)
    save(args.output, out)
    print(f"PASS: {len(results)} exact-head checks joined; "
          f"{len(stages['finalChecks'])} dependent checks built in final job")

def verify_command(args):
    plan, _, stages = validated(args)
    item = load(args.evidence)
    if any(item.get(k) != value for k, value in {
        "schemaVersion": SCHEMA, "commit": plan["commit"],
        "planDigest": plan["digest"], "stageDigest": stages["digest"],
        "graphDigest": stages["graphDigest"], "role": "join",
    }.items()):
        raise ValueError("stale final DAG evidence")
    values = item.get("checks")
    if not isinstance(values, dict) or set(values) != set(plan["checks"]):
        raise ValueError("final DAG evidence omitted checks")
    for name, check in values.items():
        if (check.get("drv") != plan["checks"][name]
                or check.get("status") != "pass" or not check.get("outputs")
                or not all(planner.STORE.fullmatch(x) for x in check["outputs"])):
            raise ValueError("invalid joined evidence for " + name)
    print(f"PASS: all {len(values)} checks, exact-head DAG and store output evidence")

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    subs = parser.add_subparsers(dest="command", required=True)
    for key, func in [("plan", plan_command), ("leaf", leaf_command),
                      ("join", join_command), ("verify", verify_command)]:
        sub = subs.add_parser(key)
        sub.set_defaults(func=func)
        sub.add_argument("--plan", required=True)
        sub.add_argument("--graph", required=True)
        sub.add_argument("--stages", required=(key != "plan"))
        if key == "plan":
            sub.add_argument("--output", required=True)
        elif key == "leaf":
            sub.add_argument("--shard", required=True)
            sub.add_argument("--prebuild", required=True)
            sub.add_argument("--archive", required=True)
            sub.add_argument("--output", required=True)
        elif key == "join":
            sub.add_argument("--leaves", required=True)
            sub.add_argument("--output", required=True)
        else:
            sub.add_argument("--evidence", required=True)
    args = parser.parse_args()
    try:
        args.func(args)
    except (ValueError, KeyError, OSError, TypeError, subprocess.CalledProcessError,
            json.JSONDecodeError) as exc:
        print(f"flake-dag-stages: {exc}", file=sys.stderr)
        raise SystemExit(1) from exc

if __name__ == "__main__":
    main()
